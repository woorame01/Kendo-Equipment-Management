package Equipment;

public class Equipment_Dobok {
	private String number;
	private String date;
	
	public Equipment_Dobok(String number, String date) {
		this.number = number;
		this.date = date;
	}
	
	public String getNumber() {
		return number;
	}
	
	public String getDate() {
		return date;
	}

}
